export function getItemsByCategory(category, customCatalog = null) {
  if (!category) return [];
  const source = (customCatalog && customCatalog.length > 0) ? customCatalog : SERVICE_CATALOG_ITEMS;
  return source.filter(item => item.category === category);
}

export function findCatalogItem(category, name, customCatalog = null) {
  const source = (customCatalog && customCatalog.length > 0) ? customCatalog : SERVICE_CATALOG_ITEMS;
  return source.find(
    i => i.category === category && i.name.toLowerCase() === (name || '').toLowerCase()
  ) || source.find(
    i => i.name.toLowerCase() === (name || '').toLowerCase()
  );
}
